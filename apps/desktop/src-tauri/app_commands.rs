// Which window may call which Raven command. Read by `build.rs` (to generate the
// `allow-<command>` permissions and the main window's permission set) and by
// `src/ipc_scope.rs` (to refuse main-only commands from any other window at run time).
//
// A command that is registered in `lib.rs` but missing from `APP_COMMANDS` is refused
// everywhere, and a unit test (`ipc_scope::tests`) fails. To add a command:
//
// 1. register it in `generate_handler!` in `src/lib.rs`;
// 2. add its name to `APP_COMMANDS` below. The main window may then call it;
// 3. only if another window needs it, add `allow-<command-with-hyphens>` to that
//    window's set in `permissions/windows.toml`;
// 4. if it starts capture, shares the screen, opens a network path, reads a file the
//    page names or touches stored sign-in secrets, also add it to `MAIN_ONLY`.

